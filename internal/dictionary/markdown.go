package dictionary

import (
	"fmt"
	"strings"
)

// markdownHead opens docs/dictionary.md: the generated-file warning, the
// heading and the sentence the Dictionary page opens with.
const markdownHead = "<!-- Generated from internal/dictionary/dictionary.yml: do not edit this file, " +
	"change dictionary.yml and run go test ./internal/dictionary " +
	"-run TestDocsDictionaryIsTheGeneratedMarkdown -update -->\n" +
	"\n# Dictionary\n\n" +
	"What each term and each number on forsgren's pages means, and where it comes from. " +
	"The entries are in alphabetical order. Every installation shows the same list " +
	"on its Dictionary page.\n"

// markdownSections are the sections of the file, in the order of the
// Dictionary page: terms first, then numbers (forsgren#577).
var markdownSections = []struct{ heading, kind string }{
	{"Terms", KindTerm},
	{"Numbers", KindNumber},
}

// Markdown is docs/dictionary.md (forsgren#578): the entries of
// dictionary.yml, read through Section as the Dictionary page reads them,
// each with its heading, its definition and its From line.
func Markdown() (string, error) {
	var b strings.Builder
	b.WriteString(markdownHead)
	for _, s := range markdownSections {
		section, err := Section(s.kind)
		if err != nil {
			return "", err
		}
		fmt.Fprintf(&b, "\n## %s\n", s.heading)
		for _, e := range section {
			fmt.Fprintf(&b, "\n### %s\n\n%s\n\nFrom: %s\n",
				markdownText(e.Heading()), markdownText(e.Definition), markdownFrom(e))
		}
	}
	return b.String(), nil
}

// markdownFrom is the entry's From line as Markdown text, a link to its
// source when it has one (forsgren#585).
func markdownFrom(e Entry) string {
	if e.Link == "" {
		return markdownText(e.From)
	}
	return "[" + markdownText(e.From) + "](" + e.Link + ")"
}

// markdownEscaper puts a backslash before each character Markdown could read
// as markup in a definition: a link, emphasis, code or HTML.
var markdownEscaper = strings.NewReplacer(
	`\`, `\\`, "`", "\\`", "*", `\*`, "_", `\_`, "[", `\[`, "]", `\]`, "<", `\<`, ">", `\>`)

// markdownText is s as Markdown text that reads as written.
func markdownText(s string) string {
	return markdownEscaper.Replace(s)
}
