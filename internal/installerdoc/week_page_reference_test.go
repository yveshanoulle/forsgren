package installerdoc

import "testing"

// TestPagesReferenceHasAWeekPageSection (forsgren#531, step 4, decisions #532 A,
// #534 A, #539 A): the pages reference describes the Week page, its counting,
// the weekend share, the en dash of a row without paths and week_page, and
// lists its meta description; the README names the page.
func TestPagesReferenceHasAWeekPageSection(t *testing.T) {
	pages := readRepoFileAsOneLine(t, "docs/pages-and-views.md")
	wantAll(t, "docs/pages-and-views.md", pages, "### The Week page",
		"The Week page (`week.html`, forsgren#531, from 1.29.0)",
		"every weekday of the `dora_days` window, not one calendar week",
		"A commit counts at its author date and a deployment at its time, both in UTC",
		"Weekend share is the commits of Saturday and Sunday out of all the commits of the row",
		"`– · 3`", "decision #539", "`Per repository`", "`week_page: false`",
		"| `week.html` | Commits and deployments per weekday and the weekend share of the commits, "+
			"per project generated by Forsgren |")
	wantAll(t, "README.md", readRepoFileAsOneLine(t, "README.md"),
		"a Week page (the commits and deployments of each weekday)")
	wantAll(t, "docs/updating-and-releases.md", readRepoFileAsOneLine(t, "docs/updating-and-releases.md"),
		"**Upgrading to 1.29.0, which adds the Week page**")
}

// TestAgentsDoNotReadTheWeekPageForThePathsCheck (forsgren#531, step 4): the
// installer and the upgrader say in one sentence that the Week page's `– · n`
// cells of a service or rule without paths are by design, so the TBD page stays
// the page the paths check reads.
func TestAgentsDoNotReadTheWeekPageForThePathsCheck(t *testing.T) {
	const sentence = "The Week page (`week.html`) is not read for this check: its `– · n` cells " +
		"for a service or rule without `paths` are by design."
	for _, file := range []repoFile{installerFile, upgraderFile} {
		wantAll(t, string(file), readRepoFileAsOneLine(t, file), sentence)
	}
}
