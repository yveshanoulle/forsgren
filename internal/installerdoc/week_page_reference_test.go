// TestPagesReferenceHasAWeekPageSection (forsgren#531, step 4, decisions #532 A,
// #534 A, #539 A): the pages reference describes the Week page, its counting,
// the Total and the shares, the en dash of a row without paths and week_page, and
// lists its meta description; the README names the page. Since forsgren#551
// both say what the page shows by default: deployments, failed deployments and
// fail rate per weekday, the commits only with week_commits: true (#548), and
// since forsgren#555 its Total and weekday cells say the same.
func TestPagesReferenceHasAWeekPageSection(t *testing.T) {
	pages := readRepoFileAsOneLine(t, "docs/pages-and-views.md")
	wantAll(t, "docs/pages-and-views.md", pages, "### The Week page",
		"The Week page (`week.html`, forsgren#531, from 1.29.0)",
		"every weekday of the `dora_days` window, not one calendar week",
		"A commit counts at its author date and a deployment at its time, both in UTC",
		"Total holds Deployments, the row's successful deployments of the window as a count",
		"**A weekday** has a Deploys cell, the share of the row's deployments on that weekday",
		"With `week_commits: true` Total and every weekday also have a Commits cell first: "+
			"in Total the count of the row's commits, under a weekday the share of them on that weekday.",
		"decision #541",
		"`–`", "decision #539", "`week_page: false`",
		"| `week.html` | Deployments, failed deployments and fail rate per weekday, "+
			"with commits when week_commits is true generated by Forsgren |")
	if strings.Contains(pages, "Total holds the row's commits and deployments") {
		t.Error("docs/pages-and-views.md still says Total holds the commits, which are off by default (forsgren#555)")
	}
	wantAll(t, "README.md", readRepoFileAsOneLine(t, "README.md"),
		"a Week page (the deployments, failed deployments and fail rate of each weekday, "+
			"and the commits when `week_commits` is true)")
	wantAll(t, "docs/updating-and-releases.md", readRepoFileAsOneLine(t, "docs/updating-and-releases.md"),
		"**Upgrading to 1.29.0, which adds the Week page**")
}

// TestAgentsDoNotReadTheWeekPageForThePathsCheck (forsgren#531, step 4): the
// installer and the upgrader say in one sentence that the Week page's `–`
// cells of a service or rule without paths are by design, so the TBD page stays
// the page the paths check reads.
func TestAgentsDoNotReadTheWeekPageForThePathsCheck(t *testing.T) {
	const sentence = "The Week page (`week.html`) is not read for this check: its `–` cells " +
		"for a service or rule without `paths` are by design."
	for _, file := range []repoFile{installerFile, upgraderFile} {
		wantAll(t, string(file), readRepoFileAsOneLine(t, file), sentence)
	}
}
