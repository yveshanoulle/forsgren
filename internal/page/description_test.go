package page

import "testing"

// generated ends every description, as Yves worded it (forsgren#208); the
// test writes it out so a wrong constant in the page cannot pass.
const generated = " generated by Forsgren"

// Each page kind's sentence, without the suffix.
const (
	doraSentence = "DORA metrics per project: deployment frequency, lead time, recovery time, " +
		"change fail rate and rework rate"
	numbersSentence = "The DORA numbers per project, without scores"
	scoringSentence = "The DORA Quick Check scores per project, with the Overall Performance"
	bothSentence    = "The DORA numbers per project, each with its DORA Quick Check score"
	issuesSentence  = "Issues opened, closed and reopened, by week, month and year"
	daysSentence    = "Issues opened, closed and reopened on each of the last 30 days"
	historySentence = "The history of the DORA metrics per project: " +
		"each half-year and the last 6 months"
	legendSentence = "How the DORA numbers are counted and scored: " +
		"the window, the bands and the scores"
	settingsSentence = "The settings of forsgren.config.yml and the value in use for each"
)

// TestEveryPageCarriesAMetaDescription (forsgren#208): the head of each page
// kind holds <meta name="description"> with one plain sentence made from the
// page's name alone; the placeholder, no-data and no-projects variants read as
// their page does, and no text names a project, a repository, a number or the
// installation's title, which a root page with another title proves.
func TestEveryPageCarriesAMetaDescription(t *testing.T) {
	titled := viewData()
	titled.Title = "Acme & Co"
	numbersRoot := viewData()
	numbersRoot.View = viewNumbers
	placeholder := Placeholder("1.9.3")
	noProjects := placeholder
	noProjects.NoProjects = true
	cases := []struct {
		name, page, sentence string
		data                 Data
	}{
		{"root", "index.html", doraSentence, viewData()},
		{"root with another title", "index.html", doraSentence, titled},
		{"root showing numbers", "index.html", numbersSentence, numbersRoot},
		{"standard", "standard/index.html", doraSentence, viewData()},
		{"numbers", "numbers/index.html", numbersSentence, viewData()},
		{"scoring", "scoring/index.html", scoringSentence, viewData()},
		{"numbers and scoring", "numbers-scoring/index.html", bothSentence, viewData()},
		{"issues", "issues.html", issuesSentence, viewData()},
		{"days", "days.html", daysSentence, viewData()},
		{"history", "history.html", historySentence, viewData()},
		{"legend", "legend.html", legendSentence, viewData()},
		{"settings", "settings.html", settingsSentence, viewData()},
		{"placeholder root", "index.html", doraSentence, placeholder},
		{"no projects root", "index.html", doraSentence, noProjects},
		{"placeholder days", "days.html", daysSentence, placeholder},
		{"placeholder history", "history.html", historySentence, placeholder},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			wantAll(t, c.page, rendered(t, c.page, c.data), `<meta name="description" content="`+c.sentence+generated+`">`)
		})
	}
}
