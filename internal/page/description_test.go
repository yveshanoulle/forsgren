package page

import (
	"strings"
	"testing"
)

// generated ends every description, as Yves worded it (forsgren#208); the
// test writes it out so a wrong constant in the page cannot pass.
const generated = " generated by Forsgren"

// Each page kind's sentence, {T} standing for the installation's title.
const (
	doraSentence = "DORA metrics of {T} per project: deployment frequency, lead time, recovery time, " +
		"change fail rate and rework rate"
	numbersSentence = "The DORA numbers of {T} per project, without scores"
	scoringSentence = "The DORA Quick Check scores of {T} per project, with the Overall Performance"
	bothSentence    = "The DORA numbers of {T} per project, each with its DORA Quick Check score"
	issuesSentence  = "Issues opened, closed and reopened in {T}, by week, month and year"
	daysSentence    = "Issues opened, closed and reopened in {T} on each of the last 30 days"
	historySentence = "The history of the DORA metrics of {T} per project: " +
		"each half-year and the last 6 months"
	legendSentence = "How the DORA numbers of {T} are counted and scored: " +
		"the window, the bands and the scores"
	settingsSentence = "The settings of forsgren.config.yml for {T} and the value in use for each"
)

// TestEveryPageCarriesAMetaDescription (forsgren#208): the head of each page
// kind holds <meta name="description"> with one plain sentence made from the
// page's name and the installation's title, HTML-escaped; the placeholder,
// no-data and no-projects variants read as their page does, and no text names
// a project, a repository or a number.
func TestEveryPageCarriesAMetaDescription(t *testing.T) {
	titled := func(data Data) Data {
		data.Title = "Acme & Co"
		return data
	}
	numbersRoot := viewData()
	numbersRoot.View = viewNumbers
	noProjects := Placeholder("1.9.0")
	noProjects.NoProjects = true
	cases := []struct {
		name, page, sentence string
		data                 Data
	}{
		{"root", "index.html", doraSentence, titled(viewData())},
		{"root showing numbers", "index.html", numbersSentence, titled(numbersRoot)},
		{"standard", "standard/index.html", doraSentence, titled(viewData())},
		{"numbers", "numbers/index.html", numbersSentence, titled(viewData())},
		{"scoring", "scoring/index.html", scoringSentence, titled(viewData())},
		{"numbers and scoring", "numbers-scoring/index.html", bothSentence, titled(viewData())},
		{"issues", "issues.html", issuesSentence, titled(viewData())},
		{"days", "days.html", daysSentence, titled(viewData())},
		{"history", "history.html", historySentence, titled(viewData())},
		{"legend", "legend.html", legendSentence, titled(viewData())},
		{"settings", "settings.html", settingsSentence, titled(viewData())},
		{"placeholder root", "index.html", doraSentence, Placeholder("1.9.0")},
		{"no projects root", "index.html", doraSentence, noProjects},
		{"placeholder days", "days.html", daysSentence, Placeholder("1.9.0")},
		{"placeholder history", "history.html", historySentence, Placeholder("1.9.0")},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			title := "forsgren"
			if c.data.Title != "forsgren" {
				title = "Acme &amp; Co"
			}
			want := strings.ReplaceAll(c.sentence, "{T}", title) + generated
			wantAll(t, c.page, rendered(t, c.page, c.data), `<meta name="description" content="`+want+`">`)
		})
	}
}
