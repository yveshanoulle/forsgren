package page

import (
	"strings"
	"testing"
)

// TestEveryPageCarriesAMetaDescription (forsgren#208): the head of each page
// kind holds <meta name="description"> with one plain sentence made from the
// page's name and the installation's title, HTML-escaped; the placeholder,
// no-data and no-projects variants read as their page does, and no text names
// a project, a repository or a number.
func TestEveryPageCarriesAMetaDescription(t *testing.T) {
	titled := func(data Data) Data {
		data.Title = "Acme & Co"
		return data
	}
	numbersRoot := viewData()
	numbersRoot.View = viewNumbers
	noProjects := Placeholder("1.9.0")
	noProjects.NoProjects = true
	const dora = "DORA metrics of Acme &amp; Co per project: deployment frequency, lead time, recovery time, " +
		"change fail rate and rework rate generated by Forsgren"
	cases := []struct {
		name, page, want string
		data             Data
	}{
		{"root", "index.html", dora, titled(viewData())},
		{"root showing numbers", "index.html", "The DORA numbers of Acme &amp; Co per project, without scores generated by Forsgren",
			titled(numbersRoot)},
		{"standard", "standard/index.html", dora, titled(viewData())},
		{"numbers", "numbers/index.html", "The DORA numbers of Acme &amp; Co per project, without scores generated by Forsgren",
			titled(viewData())},
		{"scoring", "scoring/index.html",
			"The DORA Quick Check scores of Acme &amp; Co per project, with the Overall Performance generated by Forsgren",
			titled(viewData())},
		{"numbers and scoring", "numbers-scoring/index.html",
			"The DORA numbers of Acme &amp; Co per project, each with its DORA Quick Check score generated by Forsgren", titled(viewData())},
		{"issues", "issues.html", "Issues opened, closed and reopened in Acme &amp; Co, by week, month and year generated by Forsgren",
			titled(viewData())},
		{"days", "days.html", "Issues opened, closed and reopened in Acme &amp; Co on each of the last 30 days generated by Forsgren",
			titled(viewData())},
		{"history", "history.html",
			"The history of the DORA metrics of Acme &amp; Co per project: each half-year and the last 6 months generated by Forsgren",
			titled(viewData())},
		{"legend", "legend.html",
			"How the DORA numbers of Acme &amp; Co are counted and scored: the window, the bands and the scores generated by Forsgren",
			titled(viewData())},
		{"settings", "settings.html",
			"The settings of forsgren.config.yml for Acme &amp; Co and the value in use for each generated by Forsgren", titled(viewData())},
		{"placeholder root", "index.html", strings.ReplaceAll(dora, "Acme &amp; Co", "forsgren"), Placeholder("1.9.0")},
		{"no projects root", "index.html", strings.ReplaceAll(dora, "Acme &amp; Co", "forsgren"), noProjects},
		{"placeholder days", "days.html",
			"Issues opened, closed and reopened in forsgren on each of the last 30 days generated by Forsgren", Placeholder("1.9.0")},
		{"placeholder history", "history.html",
			"The history of the DORA metrics of forsgren per project: each half-year and the last 6 months generated by Forsgren",
			Placeholder("1.9.0")},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			wantAll(t, c.page, rendered(t, c.page, c.data), `<meta name="description" content="`+c.want+`">`)
		})
	}
}
