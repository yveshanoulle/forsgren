package page

// The meta description of every page (forsgren#208): one plain sentence made
// from the page's name alone, never from a project, a repository, a number or
// the installation's title, so the head leaks nothing the page does not show.

// descriptionSuffix ends every description (forsgren#208, Yves's wording):
// no comma and no closing period.
const descriptionSuffix = " generated by Forsgren"

// descriptions are the sentences by page name, or for the index page by the
// view it shows. The standard view is the root's too.
var descriptions = map[string]string{
	viewStandard: "DORA metrics per project: deployment frequency, lead time, recovery time, " +
		"change fail rate and rework rate",
	viewNumbers:        "The DORA numbers per project, without scores",
	viewScoring:        "The DORA Quick Check scores per project, with the Overall Performance",
	viewNumbersScoring: "The DORA numbers per project, each with its DORA Quick Check score",
	IssuesPage:         "Issues opened, closed and reopened, by week, month and year",
	DaysPage:           "Issues opened, closed and reopened on each of the last 30 days",
	HistoryPage:        "The history of the DORA metrics per project: each half-year and the last 6 months",
	TbdPage: "Trunk-based development per project: the Mainline Interval, the lead times, " +
		"commits per push and per deployment and the developers",
	WeekPage: "Deployments, failed deployments and fail rate per weekday, " +
		"with commits when week_commits is true",
	legendPage:   "How the DORA numbers are counted and scored: the window, the bands and the scores",
	settingsPage: "The settings of forsgren.config.yml and the value in use for each",
}

// Description is the page's meta description (forsgren#208): the sentence of
// its name, or of the view it shows when it is the table page, the standard
// one on the root without a view.
func (p pageData) Description() string {
	key := p.Page
	if key == indexPage {
		key = p.View
	}
	sentence, ok := descriptions[key]
	if !ok {
		sentence = descriptions[viewStandard]
	}
	return sentence + descriptionSuffix
}
