package page

import "fmt"

// The meta description of every page (forsgren#208): one plain sentence made
// from the page's name and the installation's title, never from a project, a
// repository or a number, so the head leaks nothing the page does not show.

// descriptionSuffix ends every description (forsgren#208, Yves's wording):
// no comma and no closing period.
const descriptionSuffix = " generated by Forsgren"

// descriptions are the sentences by page name, or for the index page by the
// view it shows; %s is the installation's title. The standard view is the
// root's too.
var descriptions = map[string]string{
	viewStandard: "DORA metrics of %s per project: deployment frequency, lead time, recovery time, " +
		"change fail rate and rework rate",
	viewNumbers:        "The DORA numbers of %s per project, without scores",
	viewScoring:        "The DORA Quick Check scores of %s per project, with the Overall Performance",
	viewNumbersScoring: "The DORA numbers of %s per project, each with its DORA Quick Check score",
	IssuesPage:         "Issues opened, closed and reopened in %s, by week, month and year",
	DaysPage:           "Issues opened, closed and reopened in %s on each of the last 30 days",
	HistoryPage:        "The history of the DORA metrics of %s per project: each half-year and the last 6 months",
	"legend":           "How the DORA numbers of %s are counted and scored: the window, the bands and the scores",
	"settings":         "The settings of forsgren.config.yml for %s and the value in use for each",
}

// Description is the page's meta description (forsgren#208): the sentence of
// its name, or of the view it shows when it is the table page, the standard
// one on the root without a view.
func (p pageData) Description() string {
	key := p.Page
	if key == "index" {
		key = p.View
	}
	format, ok := descriptions[key]
	if !ok {
		format = descriptions[viewStandard]
	}
	return fmt.Sprintf(format+descriptionSuffix, p.Title)
}
